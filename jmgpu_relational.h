static jmsFEATURE_DATABASE*
j9_bronchotyphus(
    jmtUINT32 ChipID,
    jmtUINT32 ChipVersion,
    jmtUINT32 ProductID,
    jmtUINT32 EcoID,
    jmtUINT32 CustomerID
    )
{
    jmtINT entryNum = sizeof(gChipInfo) / sizeof(gChipInfo[0]);
    jmtINT i;


    for (i = 0; i < entryNum; ++i)
    {

        if ((gChipInfo[i].j9rut_ == ChipID)
            && (gChipInfo[i].j9_ginkgoes == ChipVersion)
            && (gChipInfo[i].j9_bhagat == ProductID)
            && (gChipInfo[i].j9sdu == EcoID)
            && (gChipInfo[i].j9_nascent == CustomerID)
            && (gChipInfo[i].j9_holinesses)
           )
        {
            return &gChipInfo[i];
        }
    }


    for (i = 0; i < entryNum; ++i)
    {

        if ((gChipInfo[i].j9rut_ == ChipID)
            && ((gChipInfo[i].j9_ginkgoes & 0xFFF0) == (ChipVersion & 0xFFF0))
            && (gChipInfo[i].j9_bhagat == ProductID)
            && (gChipInfo[i].j9sdu == EcoID)
            && (gChipInfo[i].j9_nascent == CustomerID)
            && (!gChipInfo[i].j9_holinesses)
           )
        {
            return &gChipInfo[i];
        }
    }

    return J9_CHYAK;
}
